// --- DITHERING ---
function drawDithered(ctx, x, y, w, h, color) {
    ctx.fillStyle = color;
    for (let py = 0; py < h; py++) {
        for (let px = 0; px < w; px++) {
            if ((px + py) % 2 === 0) {
                ctx.fillRect(x + px, y + py, 1, 1);
            }
        }
    }
}

// --- SPRITE RENDERING ---
function drawSprite24(ctx, spriteData, x, y, color) {
    if (!spriteData) return;
    ctx.fillStyle = color;
    for (let row = 0; row < 24; row++) {
        const bits = spriteData[row];
        if (!bits) continue;
        for (let col = 0; col < 24; col++) {
            if (bits & (1 << (23 - col))) {
                ctx.fillRect(x + col, y + row, 1, 1);
            }
        }
    }
}

function drawTilePattern16(ctx, patternData, x, y, color) {
    if (!patternData) return;
    ctx.fillStyle = color;
    for (let row = 0; row < 16; row++) {
        const bits = patternData[row];
        if (!bits) continue;
        for (let col = 0; col < 16; col++) {
            if (bits & (1 << (15 - col))) {
                ctx.fillRect(x + col, y + row, 1, 1);
            }
        }
    }
}

