// --- SPRITE HELPERS ---
function _s(str) {
    let v = 0;
    for (let i = 0; i < 24; i++) {
        if (i < str.length && str[i] === '#') v |= (1 << (23 - i));
    }
    return v;
}

function _t(str) {
    let v = 0;
    for (let i = 0; i < 16; i++) {
        if (i < str.length && str[i] === '#') v |= (1 << (15 - i));
    }
    return v;
}

