// --- RETRO TILE RENDERING ---
function renderRetroTile(ctx, tileType, x, y) {
    const pal = PALETTES.retro;
    switch (tileType) {
        case 0: // EMPTY
            ctx.fillStyle = pal.dark;
            ctx.fillRect(x, y, 16, 16);
            break;
        case 1: // WALL
            ctx.fillStyle = pal.light;
            ctx.fillRect(x, y, 16, 16);
            drawTilePattern16(ctx, TILE_PATTERNS.wall, x, y, pal.dark);
            break;
        case 2: // PATH
            ctx.fillStyle = pal.bg;
            ctx.fillRect(x, y, 16, 16);
            drawTilePattern16(ctx, TILE_PATTERNS.path, x, y, pal.mid);
            break;
        case 3: // GRASS
            ctx.fillStyle = pal.bg;
            ctx.fillRect(x, y, 16, 16);
            drawTilePattern16(ctx, TILE_PATTERNS.grass, x, y, pal.dark);
            break;
        case 4: // WATER
            ctx.fillStyle = pal.mid;
            ctx.fillRect(x, y, 16, 16);
            drawTilePattern16(ctx, TILE_PATTERNS.water, x, y, pal.dark);
            break;
        case 5: // DOOR
            ctx.fillStyle = pal.light;
            ctx.fillRect(x, y, 16, 16);
            drawTilePattern16(ctx, TILE_PATTERNS.door, x, y, pal.dark);
            break;
        case 6: // TREE
            ctx.fillStyle = pal.bg;
            ctx.fillRect(x, y, 16, 16);
            drawTilePattern16(ctx, TILE_PATTERNS.tree, x, y, pal.dark);
            break;
        case 7: // FENCE
            ctx.fillStyle = pal.bg;
            ctx.fillRect(x, y, 16, 16);
            drawTilePattern16(ctx, TILE_PATTERNS.fence, x, y, pal.dark);
            break;
        case 8: // FLOOR
            ctx.fillStyle = pal.light;
            ctx.fillRect(x, y, 16, 16);
            drawTilePattern16(ctx, TILE_PATTERNS.floor, x, y, pal.mid);
            break;
        default:
            ctx.fillStyle = pal.bg;
            ctx.fillRect(x, y, 16, 16);
    }
}

function renderPixelTile(ctx, tileType, x, y) {
    const colors = TILE_COLORS.pixel;
    const base = colors[tileType] || colors[0];
    ctx.fillStyle = base;
    ctx.fillRect(x, y, 16, 16);
    switch (tileType) {
        case 1:
            drawTilePattern16(ctx, TILE_PATTERNS.wall, x, y, '#3a2010');
            break;
        case 3:
            drawTilePattern16(ctx, TILE_PATTERNS.grass, x, y, '#1a5a1a');
            break;
        case 4:
            drawTilePattern16(ctx, TILE_PATTERNS.water, x, y, '#2060a0');
            break;
        case 5:
            drawTilePattern16(ctx, TILE_PATTERNS.door, x, y, '#a06020');
            break;
        case 6:
            drawTilePattern16(ctx, TILE_PATTERNS.tree, x, y, '#1a5a1a');
            break;
        case 7:
            drawTilePattern16(ctx, TILE_PATTERNS.fence, x, y, '#5a4030');
            break;
        case 8:
            drawTilePattern16(ctx, TILE_PATTERNS.floor, x, y, '#8a7a6a');
            break;
    }
}

function getTileColor(tileType) {
    if (currentTheme === 'classic') return null;
    const colors = TILE_COLORS[currentTheme];
    return colors ? colors[tileType] : null;
}
